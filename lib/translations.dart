String traducir(String? nombre) {
  if (nombre == null) return '';
  return nombreEspanol[nombre] ?? nombre;
}

String getBandera(String? nombre) {
  if (nombre == null) return '🏳️';
  return bandera[nombre] ?? bandera[nombreEspanol[nombre] ?? ''] ?? '🏳️';
}

/// Devuelve true si este país tiene bandera de imagen en vez de emoji
bool tieneBanderaImagen(String? nombre) {
  if (nombre == null) return false;
  return banderaImagen.containsKey(nombre) ||
      banderaImagen.containsKey(nombreEspanol[nombre] ?? '');
}

/// Devuelve la ruta de la imagen de bandera histórica, o null si usa emoji
String? getBanderaImagenPath(String? nombre) {
  if (nombre == null) return null;
  return banderaImagen[nombre] ?? banderaImagen[nombreEspanol[nombre] ?? ''];
}
